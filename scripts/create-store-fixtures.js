"use strict";
const fs = require("node:fs");
const path = require("node:path");
const { PDFDocument, StandardFonts } = require("pdf-lib");
const { createCanvas } = require("@napi-rs/canvas");
const { writeTextDocx } = require("../desktop/backend");
async function main() {
  const output = path.resolve(__dirname, "../smoke-temp/store-input");
  fs.mkdirSync(output, { recursive: true });
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  pdf.addPage([595, 842]).drawText("SWIFTLOCAL STORE PDF\nInvoice 12345", { x: 50, y: 700, size: 24, font, lineHeight: 34 });
  fs.writeFileSync(path.join(output, "a.pdf"), await pdf.save());
  const canvas = createCanvas(1400, 900); const context = canvas.getContext("2d");
  context.fillStyle = "white"; context.fillRect(0, 0, 1400, 900); context.fillStyle = "black";
  context.font = "bold 76px Arial, sans-serif"; context.fillText("SWIFTLOCAL OCR SMOKE", 90, 220);
  context.font = 'bold 88px "Microsoft JhengHei", "Heiti TC", sans-serif'; context.fillText("香港特別行政區", 90, 410);
  context.font = "68px Arial, sans-serif"; context.fillText("HONG KONG", 90, 570);
  const png = canvas.toBuffer("image/png"); fs.writeFileSync(path.join(output, "ocr-text.png"), png);
  const scan = await PDFDocument.create(); const image = await scan.embedPng(png);
  scan.addPage([700, 450]).drawImage(image, { x: 0, y: 0, width: 700, height: 450 });
  fs.writeFileSync(path.join(output, "ocr-scan.pdf"), await scan.save());
  writeTextDocx(path.join(output, "office-smoke.docx"), "SWIFTLOCAL STORE DOCX\nInvoice 12345");
  const wav = Buffer.alloc(44 + 16000);
  wav.write("RIFF"); wav.writeUInt32LE(wav.length - 8, 4); wav.write("WAVEfmt ", 8); wav.writeUInt32LE(16, 16);
  wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28);
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write("data", 36); wav.writeUInt32LE(16000, 40);
  fs.writeFileSync(path.join(output, "tone.wav"), wav);
  console.log(`Created synthetic Store fixtures: ${output}`);
}
if (require.main === module) main().catch(error => { console.error(error); process.exitCode = 1; });
